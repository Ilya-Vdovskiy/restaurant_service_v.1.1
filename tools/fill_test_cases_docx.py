def body_text(element) -> str:
    return "".join(node.text or "" for node in element.iter() if node.tag == qn("w:t")).strip()


def set_cell_text(cell, text: str) -> None:
    paragraphs = cell.paragraphs
    for paragraph in paragraphs[1:]:
        paragraph._element.getparent().remove(paragraph._element)

    paragraph = cell.paragraphs[0]
    paragraph.clear()
    lines = str(text).split("\n")
    run = paragraph.add_run(lines[0] if lines else "")
    for line in lines[1:]:
        run.add_break()
        run.add_text(line)


def fill_table(table, case: dict[str, object]) -> None:
    rows_needed = 8 + len(case["steps"])
    while len(table.rows) < rows_needed:
        table.add_row()
    while len(table.rows) > rows_needed:
        tr = table.rows[-1]._tr
        tr.getparent().remove(tr)

    idea = f"Идея: {case['idea']}\nВходные параметры: {case['input']}"
    precondition = case["precondition"]

    values = [
        ["ID тест-кейса/Приоритет", case["id"], case["id"], str(case["priority"])],
        [idea, idea, idea, idea],
        ["История редактирования", "История редактирования", "История редактирования", "История редактирования"],
        ["Создан 10/06/2026 Вдовский Илья", "Создан 10/06/2026 Вдовский Илья", "Новый тест кейс", "Новый тест кейс"],
        ["Предусловие", "Предусловие", "Предусловие", "Предусловие"],
        [precondition, precondition, precondition, precondition],
        ["Выполнимая часть", "Выполнимая часть", "Выполнимая часть", "Выполнимая часть"],
        ["Список команд", "Ожидаемый результат", "Ожидаемый результат", "Результат теста"],
    ]

    for row_idx, row_values in enumerate(values):
        for col_idx, value in enumerate(row_values):
            set_cell_text(table.cell(row_idx, col_idx), value)

    for offset, step in enumerate(case["steps"], start=8):
        action, expected = step
        row_values = [f"{offset - 7}) {action}", expected, expected, "passed"]
        for col_idx, value in enumerate(row_values):
            set_cell_text(table.cell(offset, col_idx), value)


